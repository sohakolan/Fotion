import { JSDOM, VirtualConsole } from 'jsdom';
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';

const html = readFileSync('dist/index.html', 'utf8');
const script = html.match(/src="(\/assets\/[^\"]+\.js)"/)[1];
const errors = [];
const virtualConsole = new VirtualConsole();
virtualConsole.on('jsdomError', e => errors.push(e.message));
const dom = new JSDOM('<!doctype html><html><body><div id="root"></div></body></html>', { url: 'http://localhost:5173', runScripts: 'outside-only', pretendToBeVisual: true, virtualConsole });
const w = dom.window;
const page = { id: 'test.md', title: 'Page de vérification', icon: '📝', parent: null, favorite: false, cover: '', content: '# Titre\n\nPremier\n\nSecond\n\nTroisième', version: 'one', updated: new Date().toISOString(), trashed: false };
let saves = [];
w.fetch = async (_url, options) => {
  if (options?.method === 'PUT') { const saved = { ...JSON.parse(options.body), version: `saved-${saves.length}` }; saves.push(saved); return { ok: true, json: async () => saved }; }
  return { ok: true, json: async () => [page] };
};
w.scrollBy = () => {};
w.ResizeObserver = class { observe() {} unobserve() {} disconnect() {} };
w.HTMLElement.prototype.scrollTo = function() {};
w.HTMLElement.prototype.scrollIntoView = function() {};
const rect = (top, left = 400, width = 650, height = 30) => ({ top, left, bottom: top + height, right: left + width, width, height, x: left, y: top, toJSON() {} });
w.Range.prototype.getBoundingClientRect = () => rect(200);
w.Range.prototype.getClientRects = () => [rect(200)];
w.eval(readFileSync(`dist${script}`, 'utf8'));
const settle = () => new Promise(resolve => setTimeout(resolve, 30));
await settle();
assert.equal(w.document.querySelector('.page-title').value, page.title);
const root = w.document.querySelector('.prose');
assert.ok(root);
root.getBoundingClientRect = () => rect(200, 400, 650, 400);
w.document.querySelector('.main-scroll').getBoundingClientRect = () => rect(40, 240, 1000, 800);
function geometry() {
  [...root.children].forEach((element, i) => { element.getBoundingClientRect = () => rect(200 + i * 40); });
}
geometry();
w.document.elementFromPoint = (_x, y) => [...root.children].find(el => y >= el.getBoundingClientRect().top && y <= el.getBoundingClientRect().bottom) || root;
const mouse = (type, element, x, y) => element.dispatchEvent(new w.MouseEvent(type, { bubbles: true, cancelable: true, clientX: x, clientY: y, button: 0 }));
const pointer = (type, element, x, y) => element.dispatchEvent(new w.PointerEvent(type, { bubbles: true, cancelable: true, clientX: x, clientY: y, button: 0, pointerId: 1 }));
const paragraphs = () => [...root.querySelectorAll(':scope > p')].map(p => p.textContent);
const initial = paragraphs();
mouse('mousemove', root.children[1], 420, 250);
const grip = w.document.querySelector('.block-grip');
assert.ok(grip, 'A paragraph hover exposes its drag handle');
pointer('pointerdown', grip, 379, 250);
pointer('pointermove', w, 450, 345);
assert.ok(w.document.querySelector('.block-drop-line'), 'Dragging shows the insertion line');
assert.ok(w.document.querySelector('.block-drag-preview'), 'Dragging shows a compact preview');
pointer('pointerup', w, 450, 345);
assert.deepEqual(paragraphs(), ['Second', 'Troisième', 'Premier']);
assert.equal(w.document.querySelector('.block-drop-line'), null);
assert.equal(w.document.querySelector('.block-menu'), null, 'Dropping does not open the click menu');
geometry();
mouse('mousemove', root.children[1], 420, 250);
const grip2 = w.document.querySelector('.block-grip');
pointer('pointerdown', grip2, 379, 250);
pointer('pointermove', w, 450, 345);
w.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
pointer('pointerup', w, 450, 345);
assert.deepEqual(paragraphs(), ['Second', 'Troisième', 'Premier'], 'Escape cancels a move');
mouse('mousemove', root.children[1], 420, 250);
const clickGrip = w.document.querySelector('.block-grip');
pointer('pointerdown', clickGrip, 379, 250);
pointer('pointerup', w, 379, 250);
mouse('click', clickGrip, 379, 250);
assert.ok(w.document.querySelector('.block-menu'), 'Clicking the handle opens the block menu');
const transform = [...w.document.querySelectorAll('.block-menu button')].find(b => b.textContent.includes('Transformer en'));
mouse('click', transform, 400, 280);
const heading = [...w.document.querySelectorAll('.transform-options button')].find(b => b.textContent.includes('Titre 2'));
mouse('click', heading, 400, 300);
assert.equal(root.querySelector('h2')?.textContent, 'Second', 'Block conversion preserves its text');
await new Promise(resolve => setTimeout(resolve, 650));
assert.ok(saves.at(-1).content.includes('## Second'), 'The converted and moved document is saved as Markdown');
assert.deepEqual(errors, []);
assert.notDeepEqual(paragraphs(), initial);
console.log('DOM smoke check passed: rendering, hover handles, pointer drag, insertion line, cancel, click menu, block conversion, autosave.');
dom.window.close();
