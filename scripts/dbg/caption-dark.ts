import { chromium } from '@playwright/test';
const flag = 'data:image/svg+xml;base64,' + Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="400" height="240"><rect width="400" height="240" fill="#57a08c"/></svg>').toString('base64');
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
const response = await page.context().request.post('http://127.0.0.1:5175/api/pages', { data: { title: 'Sonde sombre', icon: '🖼️', parent: null, favorite: false, cover: '', content: `![alt](${flag}) <!-- fotion:image %7B%22caption%22%3A%22Une%20belle%20l%C3%A9gende%22%7D -->\n`, trashed: false } });
const created = await response.json();
await page.addInitScript((id: any) => localStorage.setItem('fotion-active', id as any), created.id);
await page.goto('http://127.0.0.1:5175');
await page.waitForSelector('.prose figure.image-block', { timeout: 8000 });
await page.evaluate(`(() => { document.documentElement.setAttribute('data-theme','dark'); })()`);
await page.waitForTimeout(200);
const res = await page.evaluate(`(() => {
  const cap = document.querySelector('.prose figcaption');
  const st = getComputedStyle(cap);
  const r = cap.getBoundingClientRect();
  const above = document.elementFromPoint(r.left + 30, r.top + 8);
  return { rect: [r.left, r.top, r.width, r.height], topmost: above?.tagName + '.' + String(above?.className).slice(0, 40), capBg: st.backgroundColor };
})()`);
console.log(JSON.stringify(res, null, 1));
await page.screenshot({ path: 'test-results/caption-dark.png' });
await browser.close();
